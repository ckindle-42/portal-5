def persona_is_role(persona: dict) -> bool:
    """True when the YAML says this persona is delivered as a slash-command role."""
    return persona.get("delivery") == "role"


def role_prompt_payload(persona: dict) -> dict[str, str]:
    """Open WebUI v0.12.3 PromptForm. `name` is the slash-menu title; content is `/slug `."""
    slug = str(persona.get("slug") or "")
    return {
        "command": slug,
        "name": str(persona.get("name") or slug),
        "content": f"/{slug} ",
    }


def _load_persona_yaml(personas_dir: Path) -> list[dict]:
    import yaml as _yaml

    if not personas_dir.exists():
        return []
    loaded: list[dict] = []
    for path in sorted(personas_dir.glob("*.yaml")):
        try:
            raw = _yaml.safe_load(path.read_text()) or {}
        except Exception as exc:
            print(f"  Skip {path.name}: parse error — {exc}")
            continue
        if isinstance(raw, dict):
            raw.setdefault("slug", path.stem)
            loaded.append(raw)
    return loaded


async def _fetch_prompts(client: httpx.AsyncClient, token: str) -> list[dict]:
    """GET /api/v1/prompts/ — a list on v0.12.3, or a paged {items|data} envelope."""
    try:
        resp = await client.get(
            f"{OPENWEBUI_URL}/api/v1/prompts/", headers=auth_headers(token), timeout=10.0
        )
    except Exception as exc:
        print(f"  Warning: could not list prompts: {exc}")
        return []
    if resp.status_code != 200:
        print(f"  Warning: could not list prompts: HTTP {resp.status_code}")
        return []
    data = resp.json()
    if isinstance(data, list):
        return [item for item in data if isinstance(item, dict)]
    if isinstance(data, dict):
        items = data.get("items") or data.get("data") or []
        return [item for item in items if isinstance(item, dict)]
    return []


async def _delete_role_model_presets(
    client: httpx.AsyncClient,
    token: str,
    role_slugs: list[str],
    preset_ids: set[str],
) -> None:
    """Remove OWUI model presets for roles. Pipeline connection ids are left alone."""
    for slug in role_slugs:
        if slug not in preset_ids:
            continue
        try:
            resp = await client.post(
                f"{OPENWEBUI_URL}/api/v1/models/model/delete",
                json={"id": slug},
                headers=auth_headers(token),
                timeout=10.0,
            )
        except Exception as exc:
            print(f"  Warning: could not remove role preset {slug}: {exc}")
            continue
        if resp.status_code in (200, 201):
            print(f"  Removed role model preset: {slug}")
        else:
            print(f"  Warning: could not remove role preset {slug}: HTTP {resp.status_code}")


async def create_role_prompts_async(
    client: httpx.AsyncClient, token: str, personas_dir: Path
) -> None:
    """Seed one prompt-library entry per role: command=slug, content=`/slug `."""
    print("\nCreating Role Prompts...")
    roles = [
        persona
        for persona in _load_persona_yaml(personas_dir)
        if persona_is_role(persona) and persona.get("slug")
    ]
    if not roles:
        print("  Skipping — no delivery: role personas")
        return
    by_command = {str(item.get("command")): item for item in await _fetch_prompts(client, token)}
    created = updated = skipped = failed = 0
    for persona in roles:
        payload = role_prompt_payload(persona)
        current = by_command.get(payload["command"])
        unchanged = (
            current is not None
            and current.get("name") == payload["name"]
            and current.get("content") == payload["content"]
        )
        if unchanged:
            skipped += 1
            continue
        if current is not None and current.get("id"):
            url = f"{OPENWEBUI_URL}/api/v1/prompts/id/{current['id']}/update"
            body: dict = payload
            action = "updated"
        else:
            url = f"{OPENWEBUI_URL}/api/v1/prompts/create"
            body = {**payload, "access_grants": []}
            action = "created"
        try:
            resp = await client.post(url, json=body, headers=auth_headers(token), timeout=10.0)
        except Exception as exc:
            print(f"  Failed {payload['command']}: {exc}")
            failed += 1
            continue
        if resp.status_code not in (200, 201):
            print(f"  Failed {payload['command']}: HTTP {resp.status_code} {resp.text[:160]}")
            failed += 1
            continue
        print(f"  {action.capitalize()} role prompt: {payload['command']}")
        if action == "created":
            created += 1
        else:
            updated += 1
    print(
        f"  Role prompts: {created} created, {updated} updated, "
        f"{skipped} unchanged, {failed} failed"
    )


def _persona_skips_disabled_variant(persona: dict) -> bool:
    """True when the persona's variant module is off, so it is not seeded."""
    variant = persona.get("variant")
    workspace = persona.get("workspace_model")
    if not variant or not workspace:
        return False
    from portal.platform.wiki.adapters.modules import is_workspace_disabled

    return is_workspace_disabled(f"{workspace}::{variant}")


def persona_tool_ids(
    persona: dict, workspace_model: str, ws_raw_tools: dict[str, list[str]]
) -> list[str]:
    """tools_allow replaces, tools_deny subtracts; the persona's variant resolves first
    (`workspace::variant`) — the pipeline's _resolve_persona_tools rule."""
    variant = persona.get("variant")
    workspace_id = f"{workspace_model}::{variant}" if variant else workspace_model
    ws_tools = ws_raw_tools.get(workspace_id, ws_raw_tools.get(workspace_model, []))
    allow = persona.get("tools_allow")
    effective = set(ws_tools) if allow is None else set(allow)
    return _uwt.compute_tool_ids(sorted(effective - set(persona.get("tools_deny") or [])))


def persona_preset_payload(
    persona: dict,
    stem: str,
    ws_raw_tools: dict[str, list[str]],
    prompts_dir: Path = PERSONA_PROMPTS_DIR,
) -> dict | None:
    """The model preset seed_personas_async creates for one persona file, or None when it
    is skipped (role, disabled variant, unreadable template). The preset drift checker
    reads this same builder, so its expectation cannot diverge from what a seed writes."""
    if persona_is_role(persona) or _persona_skips_disabled_variant(persona):
        return None
    template = persona.get("prompt_template")
    if template:
        try:
            system_prompt = (prompts_dir / f"{template}.txt").read_text()
        except OSError:
            return None
    else:
        system_prompt = persona.get("system_prompt", "")
    slug = persona.get("slug", stem)
    name = persona.get("name", slug)
    workspace_model = persona.get("workspace_model") or "dolphin-llama3:8b"
    return {
        "id": slug,
        "name": name,
        # base_model_id must be non-null for OW v0.6.5 get_models() filter
        # (WHERE base_model_id IS NOT NULL selects presets vs base models)
        "base_model_id": workspace_model,
        "meta": {
            "description": f"Portal persona: {name}",
            "profile_image_url": "",
            "toolIds": persona_tool_ids(persona, workspace_model, ws_raw_tools),
            "tags": [{"name": persona.get("category", "general")}],
        },
        "params": {
            "system": system_prompt,
            "model": workspace_model,
            **(
                {"enable_web_search": True}
                if workspace_model
                in {
                    "auto",
                    "auto-research",
                    "auto-security",
                    "auto-reasoning",
                    "auto-compliance",
                }
                # auto-redteam/auto-blueteam removed: folded into
                # auto-security's variants (already covered above)
                # since BUILD_PROGRAM_COLLAPSE_V1.md Phase 6 — no
                # persona's workspace_model is literally those
                # strings anymore, so the entries were dead.
                else {}
            ),
        },
        # Explicit []: /model/update re-validates ModelForm and 500s when this is omitted.
        "access_grants": [],
    }


async def seed_attachment_filter_async(client: httpx.AsyncClient, token: str) -> None:
    """Seed the global inlet filter that carries attachment paths to the pipeline.

    Reads imports/openwebui/functions/<id>.json. v0.12.5 creates functions with
    is_active=False and is_global=False, so both are toggled on when missing
    (the toggle endpoints flip, so they run only when the state is wrong).
    Content updates ride /id/{id}/update only when the stored source differs —
    the same reconcile rule as the role prompts."""
    spec_file = FUNCTIONS_DIR / f"{ATTACHMENT_FILTER_ID}.json"
    print("\nSeeding attachment-path filter...")
    if not spec_file.exists():
        print(f"  Skipping - {spec_file} not found")
        return
    spec = json.loads(spec_file.read_text())
    fid = spec["id"]
    payload = {
        "id": fid,
        "name": spec.get("name", fid),
        "content": spec.get("content", ""),
        "meta": {"description": spec.get("meta", {}).get("description", "")},
    }
    try:
        resp = await client.get(
            f"{OPENWEBUI_URL}/api/v1/functions/id/{fid}", headers=auth_headers(token), timeout=10.0
        )
        existing = resp.json() if resp.status_code == 200 else None
        if existing is None:
            resp = await client.post(
                f"{OPENWEBUI_URL}/api/v1/functions/create",
                json=payload,
                headers=auth_headers(token),
                timeout=10.0,
            )
            if resp.status_code not in (200, 201):
                print(f"  Failed to create {fid}: HTTP {resp.status_code} {resp.text[:150]}")
                return
            existing = resp.json()
            print(f"  Created: {fid}")
        elif existing.get("content") != payload["content"]:
            resp = await client.post(
                f"{OPENWEBUI_URL}/api/v1/functions/id/{fid}/update",
                json=payload,
                headers=auth_headers(token),
                timeout=10.0,
            )
            if resp.status_code not in (200, 201):
                print(f"  Failed to update {fid}: HTTP {resp.status_code}")
                return
            print(f"  Updated: {fid}")
        for flag, endpoint in (("is_active", "toggle"), ("is_global", "toggle/global")):
            if not existing.get(flag):
                resp = await client.post(
                    f"{OPENWEBUI_URL}/api/v1/functions/id/{fid}/{endpoint}",
                    headers=auth_headers(token),
                    timeout=10.0,
                )
                if resp.status_code not in (200, 201):
                    print(f"  Failed to set {flag} on {fid}: HTTP {resp.status_code}")
                    return
        if not (existing.get("is_active") and existing.get("is_global")):
            print(f"  Enabled as a global filter: {fid}")
    except Exception as e:
        print(f"  Error seeding {fid}: {e}")


async def create_persona_presets_async(
    client: httpx.AsyncClient, token: str, personas_dir: Path
) -> None:
    """Create Open WebUI model presets from persona YAML files.

    P5: parallelizes all POSTs via asyncio.gather — faster seeding.
    """
    import yaml as _yaml

    print("\nCreating Persona Model Presets...")
    if not personas_dir.exists():
        print(f"  Skipping — {personas_dir} not found")
        return

    persona_files = sorted(personas_dir.glob("*.yaml"))
    if not persona_files:
        print("  Skipping — no persona YAML files found")
        return

    # /export is the full preset row (the public list strips system prompts).
    # It omits pipeline connections. A persona slug that is only a connection id
    # must not be created or deleted — that id is not a preset Portal owns.
    exported: dict[str, dict] = {}
    preset_ids: set[str] = set()
    for attempt in range(3):
        try:
            resp = await client.get(
                f"{OPENWEBUI_URL}/api/v1/models/export", headers=auth_headers(token)
            )
            if resp.status_code == 200:
                for raw in _rows_of(resp.json()):
                    row = normalize_preset(raw)
                    if row["id"]:
                        exported[row["id"]] = row
                        preset_ids.add(row["id"])
                break
        except Exception as e:
            if attempt == 2:
                print(f"  Warning: could not fetch presets after 3 attempts: {e}")
            else:
                await asyncio.sleep(1)

    base_ids: set[str] = set()
    try:
        resp2 = await client.get(f"{OPENWEBUI_URL}/api/models", headers=auth_headers(token))
        if resp2.status_code == 200:
            base_data = resp2.json()
            base_items = base_data.get("data", []) if isinstance(base_data, dict) else []
            for raw in base_items:
                if isinstance(raw, dict) and raw.get("id"):
                    base_ids.add(raw["id"])
    except Exception:
        pass  # Non-critical — /export already covers presets

    # workspace-id -> raw tools list, for resolving each persona's effective
    # tool set (see _uwt import at module level).
    _ws_raw_tools = _uwt.load_workspace_raw_tools()

    # Build persona payloads first (file reads, not network I/O)
    persona_payloads = []
    role_slugs: list[str] = []
    for f in persona_files:
        try:
            persona = _yaml.safe_load(f.read_text())
        except Exception as e:
            print(f"  Skip {f.name}: parse error — {e}")
            continue
        slug = persona.get("slug", f.stem)
        if persona_is_role(persona):
            role_slugs.append(slug)
            continue
        if _persona_skips_disabled_variant(persona):
            print(f"  Skip {slug}: variant module disabled")
            continue
        payload = persona_preset_payload(persona, f.stem, _ws_raw_tools)
        if payload is None:
            print(f"  Skip {f.name}: prompt_template {persona.get('prompt_template')!r} unreadable")
            continue
        persona_payloads.append(payload)

    await _delete_role_model_presets(client, token, role_slugs, preset_ids)
    plan = persona_seed_actions(persona_payloads, exported, base_ids, force=FORCE_RESEED)
    counts = await _apply_persona_plan(
        client, token, plan, {row["id"]: row for row in persona_payloads}, exported
    )
    if FORCE_RESEED:
        print(
            f"  Done: {counts['reseed']} reseeded, {counts['create']} created, "
            f"{counts['delete']} retired deleted, {counts['fail']} failed"
        )
    else:
        print(
            f"  Done: {counts['create']} created, {counts['update']} updated, "
            f"{counts['skip']} unchanged, {counts['fail']} failed"
        )


