async def create_workspaces_async(client: httpx.AsyncClient, token: str) -> None:
    """Create Portal workspace presets in Open WebUI."""
    print("\nCreating Workspaces...")

    # Ensure workspace toolIds are current before seeding
    try:
        _uwt.main()
    except Exception as e:
        import logging

        logging.getLogger(__name__).warning("Could not update workspace toolIds: %s", e)

    if not WORKSPACES_DIR.exists():
        print(f"  Skipping - {WORKSPACES_DIR} not found")
        return

    ws_files = sorted(WORKSPACES_DIR.glob("workspace_*.json"))
    if not ws_files:
        print("  Skipping - no workspace files found")
        return

    # Get existing workspaces
    # Use /api/v1/models (not /export or /list): /list is paginated (30/page)
    # and would miss models beyond page 1; /export silently omits overlay-style
    # presets (base_model_id=None, matching a pipeline connection by id) even
    # though they exist and GET-by-id returns them — confirmed live 2026-08-27,
    # this caused every existing workspace preset to be (wrongly) re-attempted
    # via CREATE instead of UPDATE, which then 401s on OWUI's id-collision
    # check and gets reported as a plain failure.
    existing_names: set[str] = set()
    # Overlay-style presets (base_model_id=None) with no matching workspace
    # file are orphans — this creator is the only thing that ever sets
    # base_model_id=None (see the payload below), so any such id no longer
    # backed by a workspace_*.json is safe to delete (e.g. a workspace that
    # was renamed or dropped — found live 2026-08-27, its old preset stayed
    # in OWUI indefinitely because nothing ever deleted it).
    overlay_ids: set[str] = set()
    for attempt in range(3):
        try:
            resp = await client.get(
                f"{OPENWEBUI_URL}/api/v1/models",
                headers=auth_headers(token),
            )
            if resp.status_code == 200:
                data = resp.json()
                # Handle both list and dict response formats safely
                models = (
                    data
                    if isinstance(data, list)
                    else (data.get("items") or data.get("data") or [])
                )
                for m in models:
                    if isinstance(m, dict):
                        mid = m.get("id", "")
                        existing_names.add(mid)
                        info = m.get("info")
                        if isinstance(info, dict) and info.get("base_model_id") is None:
                            overlay_ids.add(mid)
                break  # Success — exit retry loop
        except Exception as e:
            if attempt == 2:
                print(f"  Warning: could not check existing models after 3 attempts: {e}")
            else:
                await asyncio.sleep(1)

    # /api/v1/models strips system prompts (public_model_params). /base is the full
    # DB row for overlay presets (base_model_id is None), which is what the diff reads.
    base_records, base_readable = await _load_base_presets(client, token)

    created = updated = unchanged = failed = 0
    for ws_file in ws_files:
        ws = json.loads(ws_file.read_text())
        ws_id = ws.get("id", "")
        ws_name = ws.get("name", ws_id)
        # base_model_id=None overlays this preset on the pipeline model of the same id.
        # access_grants must be []: /model/update re-validates ModelForm and 500s on None.
        payload = {
            "id": ws_id,
            "name": ws_name,
            "base_model_id": None,
            "meta": ws.get("meta", {}),
            "params": ws.get("params", {}),
            "access_grants": [],
        }
        action = workspace_seed_action(
            payload,
            base_records.get(ws_id),
            exists=ws_id in existing_names,
            force=FORCE_RESEED,
            record_readable=base_readable,
        )
        if action == "skip":
            unchanged += 1
            continue
        try:
            status, _text = await _apply_preset_action(
                client, token, action, payload, base_records.get(ws_id), "workspace"
            )
        except Exception as exc:
            print(f"  Error {ws_name}: {exc}")
            failed += 1
            continue
        if status in (200, 201):
            print(f"  {action.capitalize()}: {ws_name}")
            if action == "create":
                created += 1
            else:
                updated += 1
        else:
            print(f"  {action} failed {ws_name}: HTTP {status}")
            failed += 1

    print(
        f"  Workspaces: {created} created, {updated} updated, "
        f"{unchanged} unchanged, {failed} failed"
    )

    current_ws_ids = {json.loads(f.read_text()).get("id", "") for f in ws_files}
    # Scope orphan-deletion strictly to ids config/portal.yaml has ever known
    # as a workspace (includes bench-* ids, which never get a file since
    # they're expose_to_owui:false but can still have old live presets from
    # before that flag existed) — never touch an OWUI system model like
    # "arena-model", which also happens to have base_model_id=None.
    known_ws_ids = set(_uwt.load_workspace_raw_tools().keys())
    orphans = overlay_ids & (known_ws_ids - current_ws_ids)
    for ws_id in sorted(orphans):
        try:
            resp = await client.post(
                f"{OPENWEBUI_URL}/api/v1/models/model/delete",
                json={"id": ws_id},
                headers=auth_headers(token),
                timeout=10.0,
            )
            if resp.status_code in (200, 201):
                print(f"  Removed orphaned workspace preset: {ws_id}")
            else:
                print(
                    f"  Warning: could not remove orphaned preset {ws_id}: HTTP {resp.status_code}"
                )
        except Exception as e:
            print(f"  Warning: could not remove orphaned preset {ws_id}: {e}")


