# Accumulator for daily summary (updated by _record_response_time, reset by _save_state)
_total_response_time_ms: float = 0.0


def _record_response_time(model: str, workspace: str, duration_seconds: float) -> None:
    """Record end-to-end response time for one request.

    Updates the Prometheus histogram ``_response_time_seconds``
    (per-model/workspace buckets for Grafana) and the module-level
    aggregate ``_total_response_time_ms``. The aggregate is divided
    by the request count in the daily summary to produce average
    response time.

    Failure handling: bare except → ``logger.debug``. A metric
    failure must not break the request path.

    Args:
        model: Concrete model id.
        workspace: Workspace id from the request.
        duration_seconds: End-to-end time from request received to
            last byte sent.
    """
    try:
        _response_time_seconds.labels(model=model, workspace=workspace).observe(duration_seconds)
        # Exclude bench-* traffic from daily summary (cold model loads inflate response times)
        if not workspace.startswith("bench-"):
            global _total_response_time_ms
            _total_response_time_ms += duration_seconds * 1000
    except Exception as e:
        logger.debug("Failed to record response time: %s", e)


def _record_no_answer(workspace: str, reason: str, client: str, path: str) -> None:
    """Record one turn no candidate could serve (framing lives in router/no_answer.py)."""
    try:
        _no_answer_total.labels(workspace=workspace, reason=reason, client=client, path=path).inc()
    except Exception as e:
        logger.debug("Failed to record no-answer metric: %s", e)
